// Builds a SQL migration that loads the menu sheet (data-sheet/*.csv) into the database:
// menu_category, menu_item, option_group and option_value (SRS Table 4-1). Prices become centavos.
//
//   node scripts/menu-to-sql.mjs                 writes supabase/migrations/<timestamp>_menu_from_csv.sql
//   node scripts/menu-to-sql.mjs path/to/out.sql writes there instead
//
// Re-running is safe: rows are upserted by id, and option groups or choices no longer on the sheet
// are removed (orders keep their own copy of option labels and prices). An item's availability is set
// only when the item is new, so a re-import never undoes a staff "Sold out" toggle (FR-OPS-04).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sheet = (name) => parseCsv(readFileSync(join(root, 'data-sheet', name), 'utf8'))

/** Same rules as src/data/menu.ts: header row, quoted cells, UTF-8 BOM. */
function parseCsv(text) {
  const rows = []
  let row = []
  let cell = ''
  let quoted = false
  const src = text.replace(/^\uFEFF/, '')
  for (let i = 0; i < src.length; i++) {
    const ch = src[i]
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') {
        cell += '"'
        i++
      } else if (ch === '"') quoted = false
      else cell += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') {
      row.push(cell)
      cell = ''
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++
      row.push(cell)
      if (row.some((c) => c.trim())) rows.push(row)
      row = []
      cell = ''
    } else cell += ch
  }
  row.push(cell)
  if (row.some((c) => c.trim())) rows.push(row)
  const [head, ...body] = rows
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()])))
}

const yes = (v) => (v ?? '').toLowerCase() === 'yes'
const list = (v) => (v ?? '').split(',').map((s) => s.trim()).filter(Boolean)
const bySort = (a, b) => Number(a.sort_order) - Number(b.sort_order)
/** Pesos on the sheet → integer centavos (SRS 3.8) */
const centavos = (v) => {
  if (v === undefined || v === '') return null
  const n = Number(v)
  if (!Number.isFinite(n) || n < 0) throw new Error(`Bad price "${v}"`)
  return Math.round(n * 100)
}

const q = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const b = (v) => (v ? 'true' : 'false')
const arr = (xs) => (xs.length ? `array[${xs.map(q).join(', ')}]::text[]` : `'{}'::text[]`)

const sections = sheet('sections.csv').sort(bySort)
const products = sheet('products.csv').filter((r) => yes(r.is_active)).sort(bySort)
const groups = sheet('option_groups.csv').sort(bySort)
const choices = sheet('option_choices.csv').sort(bySort)

const out = []
out.push(`-- Generated by scripts/menu-to-sql.mjs from data-sheet/*.csv on ${new Date().toISOString()}.`)
out.push('-- Do not edit by hand: change the sheet and run the script again.')
out.push('')

/* ----- Categories: boards and collections (FR-MNU-03) ----- */
out.push('insert into public.menu_category (category_id, title, menu_group, kind, badge_match, sort_order) values')
out.push(
  sections
    .map((s) => {
      // "collection: badge includes Best Seller"
      const m = /^collection:\s*badge includes\s+(.+)$/i.exec(s.kind)
      const kind = m ? 'collection' : 'board'
      return `  (${q(s.id)}, ${q(s.title)}, ${kind === 'board' ? q(s.menu_group) : 'null'}, '${kind}', ${m ? q(m[1].trim()) : 'null'}, ${Number(s.sort_order)})`
    })
    .join(',\n'),
)
out.push('on conflict (category_id) do update set title = excluded.title, menu_group = excluded.menu_group,')
out.push('  kind = excluded.kind, badge_match = excluded.badge_match, sort_order = excluded.sort_order, is_active = true;')
out.push('')

/* ----- Items ----- */
const sizeChoices = choices.filter((c) => c.group === 'size')
const boardIds = new Set(sections.filter((s) => s.kind === 'board').map((s) => s.id))

out.push(
  'insert into public.menu_item (item_id, category_id, kind, name, description, blurb, badges, image_url, price, is_new, is_available, is_active, sort_order) values',
)
out.push(
  products
    .map((p) => {
      if (!boardIds.has(p.section)) throw new Error(`Item ${p.id}: unknown section "${p.section}"`)
      const kind = p.kind === 'food' ? 'food' : 'drink'
      const sized = sizeChoices.some((c) => p[c.price_from] !== '' && p[c.price_from] !== undefined)
      const price = sized ? null : centavos(p.price)
      if (!sized && price === null) throw new Error(`Item ${p.id}: no price and no size prices`)
      return `  (${q(p.id)}, ${q(p.section)}, '${kind}', ${q(p.name)}, ${q(p.description) === 'null' ? "''" : q(p.description)}, ${q(p.blurb)}, ${arr(list(p.badge))}, ${q(p.image)}, ${price ?? 'null'}, ${b(yes(p.is_new))}, ${b(yes(p.is_available))}, true, ${Number(p.sort_order)})`
    })
    .join(',\n'),
)
out.push('on conflict (item_id) do update set category_id = excluded.category_id, kind = excluded.kind, name = excluded.name,')
out.push('  description = excluded.description, blurb = excluded.blurb, badges = excluded.badges, image_url = excluded.image_url,')
out.push('  price = excluded.price, is_new = excluded.is_new, is_active = true, sort_order = excluded.sort_order;')
out.push('-- Items no longer on the sheet stop showing; their order history stays')
out.push(`update public.menu_item set is_active = false where item_id not in (${products.map((p) => q(p.id)).join(', ')});`)
out.push('')

/* ----- Option groups and values, per item (SRS Table 4-1) ----- */
const applies = (rule, p) => {
  const [col, values] = rule.split('=')
  return !!values && values.split('|').includes(p[col.trim()] ?? '')
}

const groupRows = []
const valueRows = []
const groupKeys = []
const valueKeys = []
for (const p of products) {
  for (const g of groups.filter((g) => applies(g.applies_to, p))) {
    const isSize = g.id === 'size'
    let vals
    if (isSize) {
      vals = sizeChoices
        .map((c) => ({ c, price: centavos(p[c.price_from]) }))
        .filter((v) => v.price !== null)
        .map(({ c, price }) => ({ label: c.label, price, badge: c.badge, isDefault: yes(c.is_default), available: yes(c.is_available), sort: Number(c.sort_order) }))
    } else {
      vals = choices
        .filter((c) => c.group === g.id)
        .map((c) => ({ label: c.label, price: centavos(c.price_add) ?? 0, badge: c.badge, isDefault: yes(c.is_default), available: yes(c.is_available), sort: Number(c.sort_order) }))
    }
    if (!vals.length) continue
    // FR-CRT-03: a one-choice group starts on the sheet's default, else the cheapest
    if (g.pick !== 'many' && !vals.some((v) => v.isDefault)) {
      const min = Math.min(...vals.map((v) => v.price))
      vals.find((v) => v.price === min).isDefault = true
    }
    groupKeys.push(`    (${q(p.id)}, ${q(g.id)})`)
    groupRows.push(
      `  (${q(p.id)}, ${q(g.id)}, ${q(g.title)}, ${b(isSize || yes(g.required))}, '${g.pick === 'many' ? 'many' : 'one'}', ${b(isSize)}, ${Number(g.sort_order)})`,
    )
    for (const v of vals) {
      valueKeys.push(`    (${q(p.id)}, ${q(g.id)}, ${q(v.label)})`)
      valueRows.push(`  (${q(p.id)}, ${q(g.id)}, ${q(v.label)}, ${v.price}, ${q(v.badge)}, ${b(v.isDefault)}, ${b(v.available)}, ${v.sort})`)
    }
  }
}

out.push('insert into public.option_group (item_id, code, title, is_required, pick, is_size, sort_order) values')
out.push(groupRows.join(',\n'))
out.push('on conflict (item_id, code) do update set title = excluded.title, is_required = excluded.is_required,')
out.push('  pick = excluded.pick, is_size = excluded.is_size, sort_order = excluded.sort_order;')
out.push('')
out.push('-- Groups no longer on the sheet')
out.push('delete from public.option_group g where not exists (')
out.push('  select 1 from (values')
out.push(groupKeys.join(',\n'))
out.push('  ) as keep(item_id, code) where keep.item_id = g.item_id and keep.code = g.code);')
out.push('')
out.push('with v (item_id, code, label, price, badge, is_default, is_available, sort_order) as (values')
out.push(valueRows.join(',\n'))
out.push(')')
out.push('insert into public.option_value (group_id, label, price, badge, is_default, is_available, sort_order)')
out.push('select g.group_id, v.label, v.price, v.badge, v.is_default, v.is_available, v.sort_order')
out.push('from v join public.option_group g on g.item_id = v.item_id and g.code = v.code')
out.push('on conflict (group_id, label) do update set price = excluded.price, badge = excluded.badge,')
out.push('  is_default = excluded.is_default, is_available = excluded.is_available, sort_order = excluded.sort_order;')
out.push('')
out.push('-- Choices no longer on the sheet')
out.push('delete from public.option_value ov using public.option_group g where ov.group_id = g.group_id and not exists (')
out.push('  select 1 from (values')
out.push(valueKeys.join(',\n'))
out.push('  ) as keep(item_id, code, label) where keep.item_id = g.item_id and keep.code = g.code and keep.label = ov.label);')
out.push('')

const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
const file = process.argv[2] ?? join(root, 'supabase', 'migrations', `${stamp}_menu_from_csv.sql`)
writeFileSync(file, out.join('\n') + '\n')
console.log(`Wrote ${file}: ${sections.length} categories, ${products.length} items, ${groupRows.length} option groups, ${valueRows.length} option values`)
